-- LOCKERS 테이블 만들기(Creating table LOCKERS)

CREATE SEQUENCE LOCK_NO
 START WITH 1
 INCREMENT BY 1
 MINVALUE 1
 MAXVALUE 999999999
 NOCYCLE
 CACHE 20;

CREATE TABLE "LOCKERS" 
   (	"ID" NUMBER  NOT NULL , 
	"LOCATION" VARCHAR2(50 BYTE) NOT NULL, 
	"X" NUMBER(20,0), 
	"Y" NUMBER(20,0), 
	"CAPACITY" NUMBER(5,0), 
	"PRICE" NUMBER(10,0), 
	"STATUS" NUMBER(1,0) DEFAULT 1, 
	"CREATED_AT" TIMESTAMP (6) DEFAULT CURRENT_TIMESTAMP, 
	"LOCKER_CODE" NUMBER(4,0)
   ) ;


-- 트리거 제작(Create Trigger)

